  test do
    require "net/http"
    require "socket"

    assert_match "Autonovel Studio", shell_output("#{bin}/autonovel --version")
    assert_predicate libexec/"ui/dist/index.html", :exist?

    server = TCPServer.new("127.0.0.1", 0)
    port = server.addr[1]
    server.close
    pid = spawn(bin/"autonovel", "--no-browser", "--port", port.to_s,
                "--data-dir", (testpath/"data").to_s,
                out: File::NULL, err: File::NULL)
    begin
      connected = false
      30.times do
        begin
          response = Net::HTTP.get_response(URI("http://127.0.0.1:#{port}/api/projects"))
          assert_equal "200", response.code
          assert_match (testpath/"data/projects/Starter").to_s, response.body
          connected = true
          break
        rescue Errno::ECONNREFUSED
          sleep 0.5
        end
      end
      assert connected, "Studio did not start within 15 seconds"
    ensure
      Process.kill("TERM", pid) if Process.waitpid(pid, Process::WNOHANG).nil?
      Process.wait(pid) rescue Errno::ECHILD
    end
  end
