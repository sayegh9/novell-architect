  def install
    # The frontend is committed as a production build; Node is not needed at runtime.
    libexec.install Dir["*.py"], "prompts", "typeset"
    (libexec/"ui").install "ui/dist"
    venv = virtualenv_create(libexec/"venv", "python3.12")
    venv.pip_install resources
    (bin/"autonovel").write <<~SH
      #!/bin/sh
      exec "#{libexec}/venv/bin/python" "#{libexec}/autonovel_cli.py" "$@"
    SH
  end

