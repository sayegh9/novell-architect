#!/usr/bin/env python3
"""
Test script to generate a full literary novel chapter in Arabic using Gemini 2.5 Pro.
"""
import sys
from pathlib import Path
from dotenv import load_dotenv

BASE_DIR = Path(__file__).parent.resolve()
load_dotenv(BASE_DIR / ".env", override=True)

from llm import call_writer

SYSTEM_PROMPT = """أنت روائي عربي بارع متخصص في أدب الفانتازيا والواقعية السحرية بأسلوب أدبي رفيع (مستوى نجيب محفوظ، إبراهيم الكوني، وأمين معلوف).
قواعد الصياغة الصارمة:
1. تجنب تماماً الكليشيهات المبتذلة للذكاء الاصطناعي (ممنوع: "في خضم"، "نسيج من"، "ألقى بظلاله"، "جدير بالذكر"، "لم يكن مجرد بل كان"، "أخذ نفساً عميقاً").
2. اجعل الوصف حسياً ملموساً قائماً على حركة الجسد ونبض المكان (الحلق، أطراف الأصابع، احتكاك المعدن بالخشب، برودة الحجر).
3. الحوار فصيح، مقتضب، ذو نبرة واقعية مشحونة بالمعنى المبطن، بعيداً عن الخطابية الإنشائية.
4. إيقاع السرد متنوع بين الجمل القصيرة الضاغطة في لحظات التوتر، والجمل التركيبية المتدفقة في تأمل المشهد.
5. اكتب الفصل كاملاً ومفصلاً دون اختصار أو تلخيص."""

PROMPT = """اكتب الفصل الأول من رواية: "حارس الأوتار في مدينة الزجاج".

بيانات العالم:
- المكان: مدينة "بلّورية"، مدينة بُنيت أسوارها وأبراجها من ركام الزجاج المصهور الذي يُمسكه رنين الأوتار الموسيقية وأحكام الترددات الصامتة.
- الشخصيات:
  * "فارس": فتى في الثامنة عشرة، متدرب في ورشة ضبط الترددات، يمتلك أذناً حساسة تشعر بالنشاز كألم مادي في أسنانه وحرقة في حلقه.
  * "المعلم برهان": شيخ في الستين، جاف الملامح، يرتجف ساعده الأيسر من أثر داء الذبذبات الذي يصيب كبار الصناع.

مشاهد الفصل الأول:
1. المشهد الافتتاحي: فارس في جوف الورشة وقت الظهيرة، الضوء ينكسر عبر الزجاج المغبّر، يحاول موازنة وتر من البرونز المشدود فوق سندان رخامي، ومحاولة تفادي النشاز الذي يلسع صدغيه.
2. المواجهة: المعلم برهان يفحص الوتر بمطرقته الخشبية ويكتشف نشازاً دقيقاً (ربع نغمة)، يوبخ فارس بقسوة المعلم الخائف، كاشفاً أن النشاز في هذه المدينة ليس خطأً موسيقياً بل بداية تصدع في جدران القلعة.
3. التوتر الخفي: فارس يلمح ارتجاف يد معلمه التي يحاول إخفاءها في طيات عباءته الجلدية، وشعور المعلم بالخزي من ضعفه.
4. الخاتمة / الخطاف: بعد انصراف المعلم، يتولى فارس كنس برادة البرونز من جوف الورشة، ويقترب من "الباب المصمت" في أقصى الجدار الغربي—باب لم يُفتح قط، لكنه حين يضع أذنه عليه يسمع صمتاً غير طبيعي... صمتاً يبتلع الضوء والأصوات كفجوة في جسد العالم.

اكتب الفصل الأول الآن كاملاً بلغة عربية فصيحة آسرة."""

def main():
    print("Sending prompt to Gemini 2.5 Pro for Arabic chapter drafting...", file=sys.stderr)
    result = call_writer(PROMPT, system=SYSTEM_PROMPT, max_tokens=16000, temperature=0.75, timeout=300)
    
    out_dir = BASE_DIR / "chapters"
    out_dir.mkdir(exist_ok=True)
    out_path = out_dir / "ch_01_arabic_test.md"
    out_path.write_text(result, encoding="utf-8")
    
    wc = len(result.split())
    print(f"\n[✓] Chapter successfully drafted in Arabic!")
    print(f"Saved to: {out_path}")
    print(f"Word count: {wc:,} words\n")
    print("=" * 60)
    print("EXCERPT (First 400 words):")
    print("=" * 60)
    print(" ".join(result.split()[:400]) + "...\n")

if __name__ == "__main__":
    main()
